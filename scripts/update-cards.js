// Downloads the card data from upstream main and generates the site's data:
//   generated/raw/{gl,jp}.js   upstream card lists, as downloaded
//   generated/card-events.js   upstream card events (imported by the calc)
//   generated/metadata.js      per-card facts shared by both servers and LBs
//   generated/global_stats.js  Global stats, { [id]: [LB0, LB1, LB2, LB3, LB4] }
//   generated/jp_stats.js      JP stats, same shape
//   generated/SOURCE.json      which upstream commit the data came from
// Card ids are the same on both servers, so `id` links the files.
//
// Usage: pnpm update-cards
// Vite and the tests call ensureCards(), which only runs this when generated/
// doesn't exist yet.

import { existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from "node:fs"
import { dirname } from "node:path"
import { isDeepStrictEqual } from "node:util"
import { pathToFileURL } from "node:url"
import { DATA_FILES, GENERATED_DIR, REPO, ROOT, download, latestRef, toLocal } from "./lib/upstream.js"
import { NAME_FIELD, joinCards } from "../tierlist/join-cards.js"

const statsOf = ({ id, limit_break, char_name, type, group, rarity, ...stats }) => stats

// Splits the two upstream card lists into metadata + per-server stats. The
// lists must join back to exactly the input, which also proves that type,
// group, rarity and names are consistent across limit breaks and servers.
function split(lists) {
  const metadata = {}
  const stats = {}
  for (const [server, cards] of Object.entries(lists)) {
    stats[server] = {}
    for (const card of cards) {
      const meta = (metadata[card.id] ??= {
        id: card.id,
        type: card.type,
        group: card.group,
        rarity: card.rarity,
        name_en: null,
        name_jp: null,
      })
      meta[NAME_FIELD[server]] = card.char_name
      ;(stats[server][card.id] ??= [])[card.limit_break] = statsOf(card)
    }
  }
  for (const [server, cards] of Object.entries(lists)) {
    if (!isDeepStrictEqual(joinCards(server, metadata, stats[server]), cards)) {
      throw new Error(`${server}: split card data doesn't join back to the upstream list`)
    }
  }
  return { metadata, stats }
}

// One card per line keeps the files readable and diffable.
function moduleSource(comment, object) {
  const lines = Object.entries(object).map(([id, value]) => `  ${id}: ${JSON.stringify(value)},`)
  return `// ${comment}\n// Generated by scripts/update-cards.js — do not edit.\n\nexport default {\n${lines.join("\n")}\n}\n`
}

export async function updateCards() {
  const ref = await latestRef()
  console.log(`Fetching card data from ${REPO} @ ${ref.slice(0, 10)}…`)
  const sources = await download(ref, DATA_FILES)

  // Build everything in a temp dir and swap it in, so a failure never leaves
  // generated/ half-written.
  const tmp = `${ROOT}generated.tmp/`
  rmSync(tmp, { recursive: true, force: true })
  try {
    for (const file of DATA_FILES) {
      mkdirSync(dirname(tmp + file.local), { recursive: true })
      writeFileSync(tmp + file.local, toLocal(file, sources[file.upstream]))
    }
    const lists = {
      gl: (await import(pathToFileURL(`${tmp}raw/gl.js`))).default,
      jp: (await import(pathToFileURL(`${tmp}raw/jp.js`))).default,
    }
    const { metadata, stats } = split(lists)

    writeFileSync(`${tmp}metadata.js`, moduleSource("Support card facts shared by both servers, keyed by card id.", metadata))
    writeFileSync(`${tmp}global_stats.js`, moduleSource("Global support card stats: { [id]: [LB0..LB4] }.", stats.gl))
    writeFileSync(`${tmp}jp_stats.js`, moduleSource("JP support card stats: { [id]: [LB0..LB4] }.", stats.jp))
    const source = {
      repo: REPO,
      ref,
      fetched_at: new Date().toISOString(),
      cards: { total: Object.keys(metadata).length, gl: Object.keys(stats.gl).length, jp: Object.keys(stats.jp).length },
    }
    writeFileSync(`${tmp}SOURCE.json`, JSON.stringify(source, null, 2) + "\n")

    rmSync(GENERATED_DIR, { recursive: true, force: true })
    renameSync(tmp, GENERATED_DIR)
    console.log(`Wrote ${source.cards.total} cards to generated/ (${source.cards.gl} on Global, ${source.cards.jp} on JP).`)
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}

// Fetches card data only if this checkout doesn't have it yet.
export async function ensureCards() {
  if (!existsSync(`${GENERATED_DIR}SOURCE.json`)) await updateCards()
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    await updateCards()
  } catch (err) {
    console.error(`Card data update failed: ${err.message}`)
    process.exit(1)
  }
}
